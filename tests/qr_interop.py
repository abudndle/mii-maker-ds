#!/usr/bin/env python3
"""Independent verification; requires Pillow, pycryptodome and zxing-cpp."""
from pathlib import Path
import argparse,binascii,re
from PIL import Image
from Crypto.Cipher import AES
import zxingcpp
root=Path(__file__).resolve().parents[1]
a=argparse.ArgumentParser();a.add_argument('--native',type=Path);args=a.parse_args()
key=bytes.fromhex('59fc817e6446ea6190347b20e9bdce52')
if args.native:
 im=Image.open(args.native).crop((0,0,256,192));r=zxingcpp.read_barcode(im);assert r
 p=r.bytes;assert len(p)==112
 # Reconstruct the encrypted zero padding omitted by the 3DS envelope.
 counter=bytes([2])+p[:8]+bytes(4)+bytes([0,0,6]);tail=AES.new(key,AES.MODE_ECB).encrypt(counter)[8:]
 cipher=AES.new(key,AES.MODE_CCM,nonce=p[:8]+bytes(4),mac_len=16,msg_len=96)
 plain=cipher.decrypt_and_verify(p[8:96]+tail,p[96:]);assert plain[88:]==bytes(8)
 raw=plain[:12]+p[:8]+plain[12:88]
 assert len(raw)==96 and raw[0]==3 and binascii.crc_hqx(raw[:94],0)==int.from_bytes(raw[94:],'big')
 assert raw[26:46].decode('utf-16-le').rstrip('\0')=='Mii' and raw[50]==1
 print('PASS: independent ZXing + AES-CCM authentication + CFSD CRC/appearance check of QR generated by emulated ARM code')
else:
 p=(root/'validation/mii-qr-payload.bin').read_bytes();raw=bytes(int(x,16) for x in re.findall(r'0x([0-9a-f]{2})',(root/'tests/cfs_fixture.h').read_text()))
 cipher=AES.new(key,AES.MODE_CCM,nonce=p[:8]+bytes(4),mac_len=16,msg_len=96);ct=cipher.encrypt(raw[:12]+raw[20:]+bytes(8));assert ct[:88]==p[8:96] and cipher.digest()==p[96:]
 im=Image.open(root/'validation/mii-qr-photo.png');assert im.size==(400,240);r=zxingcpp.read_barcode(im);assert r and r.bytes==p
 print('PASS: independent AES-CCM 3DS padded-length/tag and exact QR decode from saved PNG')
