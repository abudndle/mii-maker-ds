#!/usr/bin/env python3
"""Generate numeric-only DS editor arrow/adjust CLAN keyframes from a private catalog."""
import argparse
import json
import math
from pathlib import Path

TRACKS = (
 ("adjust_change_y","EditEye_Decide","P_Change_00","CLPA",1,4),
 ("adjust_change_r","EditEye_Decide","P_Change_00","CLMC",4,4),
 ("adjust_change_g","EditEye_Decide","P_Change_00","CLMC",5,4),
 ("adjust_change_b","EditEye_Decide","P_Change_00","CLMC",6,4),
 ("adjust_arrow_y","EditEye_Decide","P_BtnArrowR","CLPA",1,3),
 ("adjust_arrow_hair_y","EditHair_Decide","P_BtnArrowR","CLPA",1,3),
 ("adjust_arrow_r","EditEye_Decide","P_BtnArrowR","CLMC",4,1),
 ("adjust_arrow_g","EditEye_Decide","P_BtnArrowR","CLMC",5,1),
 ("adjust_arrow_b","EditEye_Decide","P_BtnArrowR","CLMC",6,1),
)
# Original release tracks have real keyframes; Invalid is mostly a held
# material/opacity state, not an animated error pulse.
EXTRA = (
 ("adjust_release_y","EditEye_UnDecide","P_BtnArrowR","CLPA",1,1,0),
 ("adjust_release_arrow_r","EditEye_UnDecide","P_BtnArrowR","CLMC",4,2,0),
 ("adjust_release_arrow_g","EditEye_UnDecide","P_BtnArrowR","CLMC",5,2,0),
 ("adjust_release_arrow_b","EditEye_UnDecide","P_BtnArrowR","CLMC",6,2,0),
 ("adjust_release_change_r","EditEye_UnDecide","P_Change_00","CLMC",4,1,-17),
 ("adjust_release_change_g","EditEye_UnDecide","P_Change_00","CLMC",5,1,-17),
 ("adjust_release_change_b","EditEye_UnDecide","P_Change_00","CLMC",6,1,-17),
 ("adjust_invalid_change_r","EditEye_Invalid","P_Change_00","CLMC",4,1,0),
 ("adjust_invalid_change_g","EditEye_Invalid","P_Change_00","CLMC",5,1,0),
 ("adjust_invalid_change_b","EditEye_Invalid","P_Change_00","CLMC",6,1,0),
 ("adjust_invalid_arrow","EditEye_Invalid","P_BtnArrowR","CLMC",4,1,-19),
 ("adjust_invalid_alpha","EditEye_Invalid","P_Change_00","CLMC",15,1,0),
)
def q16(number):
 if not isinstance(number,(int,float)) or not math.isfinite(number):
  raise ValueError("invalid source value")
 result=round(number*65536)
 if not -(2**31)<=result<2**31:
  raise ValueError("source value outside Q16.16")
 return result

def generate(catalog):
 found={}
 for c in catalog.get("clips",[]):
  if c.get("archive")=="Editor.arc.files" and c.get("clip") in ("EditEye_Decide","EditHair_Decide","EditEye_UnDecide","EditEye_Invalid"):
   if c["clip"] in found:raise ValueError("duplicate original clip")
   expected=11 if c["clip"]=="EditEye_Invalid" else 6
   if c.get("frames")!=expected:raise ValueError("original clip length changed")
   found[c["clip"]]=c
 if len(found)!=4:raise ValueError("missing editor Decide, UnDecide or Invalid animation")
 output=["/* Numeric keyframes from original EditEye_Decide + EditHair_Decide.",
         " * Nintendo CLAN assets are not included. Generated by tools/generate_clan_adjust.py. */",
         "#ifndef MDS_CLAN_ADJUST_GENERATED_H","#define MDS_CLAN_ADJUST_GENERATED_H",
         '#include "clan_curve.h"']
 for name,clip,pane,kind,target,count in TRACKS:
  hits=[t for t in found[clip].get("tracks",[]) if
        (t.get("pane"),t.get("kind"),t.get("index"),t.get("target"),t.get("value_type"))==
        (pane,kind,0,target,2)]
  if len(hits)!=1:raise ValueError("missing/ambiguous source track: "+name)
  keys=hits[0].get("keys")
  if not isinstance(keys,list) or len(keys)!=count:
   raise ValueError("unexpected key count: "+name)
  expected_end=3 if name.startswith("adjust_change") else 1 if "arrow_y" in name or "arrow_hair_y" in name else 0
  if keys[0][0]!=0 or keys[-1][0]!=expected_end:
   raise ValueError("unexpected source span: "+name)
  previous=float("-inf");values=[]
  for key in keys:
   if not isinstance(key,list) or len(key)!=3 or key[0]<previous:
    raise ValueError("invalid source key order: "+name)
   previous=key[0]
   values.append("{"+",".join(str(q16(v)) for v in key)+"}")
  output.append("static const MdsClanKey "+name+"[]={"+",".join(values)+"};")
 for name,clip,pane,kind,target,count,frame in EXTRA:
  tracks=[t for t in found[clip].get("tracks",[]) if
          (t.get("pane"),t.get("kind"),t.get("index"),t.get("target"),t.get("value_type"))==
          (pane,kind,0,target,2)]
  if len(tracks)!=1:raise ValueError("missing/ambiguous release/invalid channel: "+name)
  keys=tracks[0].get("keys")
  if not isinstance(keys,list) or len(keys)!=count or keys[0][0]!=frame:
   raise ValueError("invalid release/invalid keys: "+name)
  if count==2 and keys[-1][0]!=1:
   raise ValueError("incorrect release end-frame: "+name)
  previous=float("-inf");values=[]
  for key in keys:
   if not isinstance(key,list) or len(key)!=3 or key[0]<previous:
    raise ValueError("invalid release/invalid order: "+name)
   previous=key[0]
   values.append("{"+",".join(str(q16(x)) for x in key)+"}")
  output.append("static const MdsClanKey "+name+"[]={"+",".join(values)+"};")
 output.append("#endif")
 return "\n".join(output)+"\n"

if __name__=="__main__":
 p=argparse.ArgumentParser(description=__doc__)
 p.add_argument("catalog",type=Path)
 p.add_argument("--output",type=Path,required=True)
 args=p.parse_args()
 args.output.write_text(generate(json.loads(args.catalog.read_text(encoding="utf-8"))),encoding="utf-8")
 print("PASS: original Editor Decide/UnDecide/Invalid source keyframes")
